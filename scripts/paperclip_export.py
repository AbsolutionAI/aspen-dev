#!/usr/bin/env python3
"""Export sanitized Paperclip company definitions into aspen-dev/paperclip/ (BEL-197).

aspen-dev is the canonical, *public* home for Paperclip company definitions and
org charts. This tool turns read-only Paperclip API dumps into reviewable,
secret-free files:

    paperclip/companies/<slug>/company.json   structure (allowlisted fields only)
    paperclip/companies/<slug>/ORG.md         human-readable org chart (mermaid)

Input directory layout (produce with read-only GETs against Paperclip):

    companies.json                 GET /api/companies
    agents-<companyId>.json        GET /api/companies/<companyId>/agents
    projects-<companyId>.json      GET /api/companies/<companyId>/projects

Sanitization is an **allowlist**: only the fields named in COMPANY_FIELDS,
AGENT_FIELDS and PROJECT_FIELDS are ever written. Adapter/runtime config,
environment, permissions, budgets/spend, ids, heartbeats and metadata are
dropped by construction. Agents that are not hired yet (``pending_approval``)
or are terminated are excluded. Volatile runtime state (idle/running/paused) is
not part of a definition and is not exported.

Usage::

    python3 scripts/paperclip_export.py --in /tmp/paperclip-dump --out paperclip/companies
    python3 scripts/paperclip_export.py --in DIR --out DIR --check   # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

SCHEMA_VERSION = 1

COMPANY_FIELDS = ("name", "issuePrefix", "description", "requireBoardApprovalForNewAgents")
AGENT_FIELDS = ("name", "role", "title", "adapterType", "capabilities")
PROJECT_FIELDS = ("name",)
EXCLUDED_AGENT_STATUSES = {"pending_approval", "terminated"}

# Defence in depth: refuse to write anything that looks like a credential even
# if it slipped into an allowlisted free-text field (e.g. a pasted token).
_SECRET_SHAPES = re.compile(
    r"(ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|xox[abp]-[0-9A-Za-z-]{10,}"
    r"|sk-[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----"
    r"|SU[A-Z0-9]{56})"
)


class SecretShapeError(ValueError):
    """Raised when an exported value matches a credential shape."""


def slugify(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return re.sub(r"-company$", "", slug) or "company"


def _load(path: Path) -> Any:
    data = json.loads(path.read_text(encoding="utf-8"))
    return data


def _as_list(data: Any, key: str) -> List[Dict[str, Any]]:
    if isinstance(data, list):
        return data
    if isinstance(data, dict) and isinstance(data.get(key), list):
        return data[key]
    raise ValueError(f"expected a list (or {{'{key}': [...]}}), got {type(data).__name__}")


def _pick(obj: Dict[str, Any], fields) -> Dict[str, Any]:
    return {f: obj.get(f) for f in fields}


def _assert_clean(value: Any, where: str) -> None:
    blob = json.dumps(value, ensure_ascii=False)
    m = _SECRET_SHAPES.search(blob)
    if m:
        raise SecretShapeError(f"credential-shaped value in {where}; refusing to export")


def build_company(company: Dict[str, Any], agents: List[Dict[str, Any]],
                  projects: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Return the sanitized definition for one company."""
    by_id = {a.get("id"): a for a in agents}
    kept = [a for a in agents if a.get("status") not in EXCLUDED_AGENT_STATUSES]
    kept_ids = {a.get("id") for a in kept}
    out_agents = []
    for a in sorted(kept, key=lambda x: (x.get("reportsTo") is not None, str(x.get("name")))):
        entry = _pick(a, AGENT_FIELDS)
        boss = a.get("reportsTo")
        entry["reportsTo"] = (
            by_id[boss].get("name") if boss in by_id and boss in kept_ids else None
        )
        out_agents.append(entry)
    definition = {
        "schemaVersion": SCHEMA_VERSION,
        **_pick(company, COMPANY_FIELDS),
        "agents": out_agents,
        "projects": sorted((_pick(p, PROJECT_FIELDS) for p in projects),
                           key=lambda p: str(p["name"])),
    }
    _assert_clean(definition, f"company {company.get('name')!r}")
    return definition


def render_org(defn: Dict[str, Any]) -> str:
    """Mermaid org chart + roster table for one company definition."""
    def node(name: str) -> str:
        return "n_" + re.sub(r"[^A-Za-z0-9]", "_", name)

    lines = [
        f"# {defn['name']} ({defn.get('issuePrefix') or '-'})",
        "",
        "<!-- Generated by scripts/paperclip_export.py — edit company.json, not this file. -->",
        "",
    ]
    if defn.get("description"):
        lines += [defn["description"], ""]
    lines += ["```mermaid", "graph TD"]
    for a in defn["agents"]:
        label = f"{a['name']}<br/>{a.get('role') or ''}".replace('"', "'")
        lines.append(f'  {node(a["name"])}["{label}"]')
    for a in defn["agents"]:
        if a.get("reportsTo"):
            lines.append(f"  {node(a['reportsTo'])} --> {node(a['name'])}")
    lines += ["```", "", "| Agent | Role | Adapter | Reports to | Title |", "|---|---|---|---|---|"]
    for a in defn["agents"]:
        title = (a.get("title") or "").replace("|", "/")
        lines.append(
            f"| {a['name']} | {a.get('role') or ''} | {a.get('adapterType') or ''} "
            f"| {a.get('reportsTo') or '—'} | {title} |"
        )
    if defn.get("projects"):
        lines += ["", "**Projects:** " + ", ".join(p["name"] for p in defn["projects"])]
    lines.append("")
    return "\n".join(lines)


def export(in_dir: Path) -> Dict[str, Dict[str, str]]:
    """Return {slug: {filename: content}} for every company in ``in_dir``."""
    companies = _as_list(_load(in_dir / "companies.json"), "companies")
    files: Dict[str, Dict[str, str]] = {}
    for c in companies:
        cid = c.get("id")
        agents = _as_list(_load(in_dir / f"agents-{cid}.json"), "agents")
        proj_path = in_dir / f"projects-{cid}.json"
        projects = _as_list(_load(proj_path), "projects") if proj_path.exists() else []
        defn = build_company(c, agents, projects)
        slug = slugify(str(c.get("name")))
        files[slug] = {
            "company.json": json.dumps(defn, indent=2, ensure_ascii=False) + "\n",
            "ORG.md": render_org(defn),
        }
    return files


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--in", dest="in_dir", required=True, type=Path)
    ap.add_argument("--out", dest="out_dir", required=True, type=Path)
    ap.add_argument("--check", action="store_true",
                    help="compare instead of writing; exit 1 when files differ")
    args = ap.parse_args(argv)
    files = export(args.in_dir)
    drift = []
    for slug, entries in files.items():
        for name, content in entries.items():
            target = args.out_dir / slug / name
            if args.check:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    drift.append(str(target))
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            print(f"wrote {target}")
    if args.check:
        for d in drift:
            print(f"drift: {d}")
        return 1 if drift else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
